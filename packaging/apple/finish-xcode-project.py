#!/usr/bin/env python3
"""
Finish the Xcode project generated by safari-web-extension-converter:
  1. app icons from the vector sources (assets/icon-source, Apple HIG grids);
  2. Privacy Manifest (PrivacyInfo.xcprivacy) in every app and extension target:
     no tracking, no tracking domains, no collected data, no required-reason APIs;
  3. App Store category (Lifestyle), version from manifest.json.
Run after packaging/apple/make-xcode-project.sh. Idempotent.
"""
import json, os, re, shutil, subprocess, sys, tempfile, uuid

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
PROJ = os.path.join(ROOT, 'apple', 'Auscultrix')
PBX = os.path.join(PROJ, 'Auscultrix.xcodeproj', 'project.pbxproj')
ICONSRC = os.path.join(ROOT, 'assets', 'icon-source')
VERSION = json.load(open(os.path.join(ROOT, 'manifest.json')))['version']

PRIVACY = """<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
\t<key>NSPrivacyTracking</key>
\t<false/>
\t<key>NSPrivacyTrackingDomains</key>
\t<array/>
\t<key>NSPrivacyCollectedDataTypes</key>
\t<array/>
\t<key>NSPrivacyAccessedAPITypes</key>
\t<array/>
</dict>
</plist>
"""

def render_svg(svg, size, out):
    tmp = tempfile.mkdtemp()
    subprocess.run(['qlmanage', '-t', '-s', '1024', '-o', tmp, svg], check=True, capture_output=True)
    png = os.path.join(tmp, os.path.basename(svg) + '.png')
    shutil.copy(png, out)
    if size != 1024:
        subprocess.run(['sips', '-z', str(size), str(size), out], check=True, capture_output=True)
    # App Store icons must not have an alpha channel on iOS
    shutil.rmtree(tmp)

def icons():
    aset = os.path.join(PROJ, 'Shared (App)', 'Assets.xcassets', 'AppIcon.appiconset')
    contents = json.load(open(os.path.join(aset, 'Contents.json')))
    mac_svg = os.path.join(ICONSRC, 'icon-macos.svg')
    ios_svg = os.path.join(ICONSRC, 'icon-ios.svg')
    for img in contents['images']:
        fn = img.get('filename')
        if not fn:
            continue
        w = int(float(img['size'].split('x')[0]) * int(img.get('scale', '1x').rstrip('x')))
        src = ios_svg if img.get('platform') == 'ios' else mac_svg
        render_svg(src, w, os.path.join(aset, fn))
    # iOS 1024 icon: flatten alpha (App Store requirement)
    ios_png = os.path.join(aset, 'universal-icon-1024@1x.png')
    if os.path.exists(ios_png):
        subprocess.run(['sips', '-s', 'format', 'jpeg', ios_png, '--out', ios_png + '.jpg'], check=True, capture_output=True)
        subprocess.run(['sips', '-s', 'format', 'png', ios_png + '.jpg', '--out', ios_png], check=True, capture_output=True)
        os.remove(ios_png + '.jpg')
    large = os.path.join(PROJ, 'Shared (App)', 'Assets.xcassets', 'LargeIcon.imageset')
    for fn in os.listdir(large):
        if fn.endswith('.png'):
            render_svg(mac_svg, 512, os.path.join(large, fn))
    icon_png = os.path.join(PROJ, 'Shared (App)', 'Resources', 'Icon.png')
    if os.path.exists(icon_png):
        render_svg(mac_svg, 256, icon_png)

def pbx_id():
    return uuid.uuid4().hex[:24].upper()

def privacy():
    s = open(PBX).read()
    if 'PrivacyInfo.xcprivacy' in s:
        return 'already present'
    files = {}
    for shared in ('Shared (App)', 'Shared (Extension)'):
        open(os.path.join(PROJ, shared, 'PrivacyInfo.xcprivacy'), 'w').write(PRIVACY)
        ref = pbx_id()
        files[shared] = ref
        s = s.replace('/* Begin PBXFileReference section */',
            '/* Begin PBXFileReference section */\n\t\t%s /* PrivacyInfo.xcprivacy */ = {isa = PBXFileReference; lastKnownFileType = text.xml; path = PrivacyInfo.xcprivacy; sourceTree = "<group>"; };' % ref, 1)
        # add to the group whose path is the shared folder
        m = re.search(r'(\t\t[0-9A-F]{24} /\* %s \*/ = \{\n\t\t\tisa = PBXGroup;\n\t\t\tchildren = \(\n)' % re.escape(shared), s)
        if not m:
            sys.exit('group not found: ' + shared)
        s = s[:m.end()] + '\t\t\t\t%s /* PrivacyInfo.xcprivacy */,\n' % ref + s[m.end():]
    # each native target: add a build file to its Resources phase
    targets = re.findall(r'\t\t([0-9A-F]{24}) /\* ([^*]+) \*/ = \{\n\t\t\tisa = PBXNativeTarget;(.*?)\n\t\t\};', s, re.S)
    for tid, name, body in targets:
        phases = re.search(r'buildPhases = \((.*?)\);', body, re.S).group(1)
        res = re.search(r'([0-9A-F]{24}) /\* Resources \*/', phases)
        if not res:
            continue
        shared = 'Shared (Extension)' if 'Extension' in name else 'Shared (App)'
        bf = pbx_id()
        s = s.replace('/* Begin PBXBuildFile section */',
            '/* Begin PBXBuildFile section */\n\t\t%s /* PrivacyInfo.xcprivacy in Resources */ = {isa = PBXBuildFile; fileRef = %s /* PrivacyInfo.xcprivacy */; };' % (bf, files[shared]), 1)
        m = re.search(r'(\t\t%s /\* Resources \*/ = \{\n\t\t\tisa = PBXResourcesBuildPhase;\n\t\t\tbuildActionMask = \d+;\n\t\t\tfiles = \(\n)' % res.group(1), s)
        s = s[:m.end()] + '\t\t\t\t%s /* PrivacyInfo.xcprivacy in Resources */,\n' % bf + s[m.end():]
    open(PBX, 'w').write(s)
    return 'added to %d targets' % len(targets)

def settings():
    s = open(PBX).read()
    s = re.sub(r'MARKETING_VERSION = [^;]+;', 'MARKETING_VERSION = %s;' % VERSION, s)
    # Safari 17 is the minimum declared in the Safari manifest
    s = re.sub(r'MACOSX_DEPLOYMENT_TARGET = [^;]+;', 'MACOSX_DEPLOYMENT_TARGET = 13.0;', s)
    s = re.sub(r'IPHONEOS_DEPLOYMENT_TARGET = [^;]+;', 'IPHONEOS_DEPLOYMENT_TARGET = 17.0;', s)
    s = re.sub(r'INFOPLIST_KEY_LSApplicationCategoryType = [^;]+;', 'INFOPLIST_KEY_LSApplicationCategoryType = "public.app-category.lifestyle";', s)
    if 'INFOPLIST_KEY_LSApplicationCategoryType' not in s:
        s = s.replace('INFOPLIST_KEY_CFBundleDisplayName = Auscultrix;', 'INFOPLIST_KEY_CFBundleDisplayName = Auscultrix;\n\t\t\t\tINFOPLIST_KEY_LSApplicationCategoryType = "public.app-category.lifestyle";')
    open(PBX, 'w').write(s)

if __name__ == '__main__':
    icons()
    print('icons: rendered from assets/icon-source')
    print('privacy manifest:', privacy())
    settings()
    print('version', VERSION, 'category lifestyle')
