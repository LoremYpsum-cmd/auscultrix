/**
 * Keys to remove from chrome.storage.local for a full erase.
 * @param {string[]} presentKeys keys currently in storage
 */
export function keysToErase(presentKeys) {
  const keep = new Set(NON_PERSONAL_LOCAL_KEYS);
  return (presentKeys || []).filter((k) => !keep.has(k));
}
