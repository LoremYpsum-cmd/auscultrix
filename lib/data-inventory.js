/** Fields of the mood analysis that may contain the person's own words. */
const FREE_TEXT_MOOD_FIELDS = ['rawInput', 'motivationInfluences', 'listenerAgeSignal'];

/**
 * Copy of the analysis that is safe to persist: no typed text, no matched
 * words. Everything else is numbers, labels or sentences generated by the app.
 * @param {object|null} mood
 */
export function persistableMood(mood) {
  if (!mood || typeof mood !== 'object') return null;
  const out = { ...mood };
  for (const k of FREE_TEXT_MOOD_FIELDS) delete out[k];
  return out;
}

