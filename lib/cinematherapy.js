/** @param {object} film */
export function filmIsWikiflix(film) {
  return Boolean(film?.wikiflixQ);
}

/** Curated commercial / discovery titles with a TMDB id (not Wikiflix-free). */
export function filmIsTmdbCatalog(film) {
  return Boolean(film?.tmdbId) && !film?.wikiflixQ;
}

/**
 * @param {'wikiflix'|'tmdb'|'all'|string} [pool]
 * @returns {object[]}
 */
export function filmsForPool(pool = 'all') {
  if (pool === 'wikiflix') {
    return THERAPEUTIC_FILMS.filter((f) => filmIsWikiflix(f));
  }
  if (pool === 'tmdb') {
    // Curated picks + complete director filmographies + affine wave
    // (verified TMDB ids). World-only by design (see director file header).
    return [...THERAPEUTIC_FILMS, ...DIRECTOR_FILMS, ...AFFINE_FILMS].filter((f) => filmIsTmdbCatalog(f));
  }
  return [...THERAPEUTIC_FILMS, ...DIRECTOR_FILMS, ...AFFINE_FILMS];
}

