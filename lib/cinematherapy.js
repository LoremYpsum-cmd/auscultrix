/**
 * Primary open URL for a free/Wikiflix (or free-first) film card.
 * @param {{ title?: string, wikiflixQ?: string|number, tmdbId?: number }} film
 * @param {import('./media-links.js').CareOpenOptions|string} [uiLocaleOrOpts]
 * @param {'free'|'paid_ok'|string} [careAccessMode]
 * @param {string} [playbackProviderId]
 */
export function tmdbUrl(
  film,
  uiLocaleOrOpts = 'en',
  careAccessMode = 'free',
  playbackProviderId = '',
) {
  return filmOpenUrl(film, uiLocaleOrOpts, careAccessMode, playbackProviderId);
}

/**
 * TMDB public movie page — discovery only (curated id, no API).
 * @param {{ title?: string, tmdbId?: number }} film
 */
export function tmdbDiscoveryUrl(film) {
  return tmdbMovieMetaUrl(film);
}

/**
 * @param {object} mood
 * @param {{
 *   count?: number,
 *   seed?: number,
 *   musicLanguageMode?: string,
 *   uiLocale?: 'it'|'en',
 *   careAccessMode?: string,
 *   filmPool?: 'wikiflix'|'tmdb'|'all',
 * }} [options]
 * @returns {object[]} top therapeutic films for this mood
 */
export function recommendFilms(mood, options = {}) {
  const pool = options.filmPool || 'all';
  const items = filmsForPool(pool);
  const opts = { ...options };
  // Wikiflix pool is always free/legal; TMDB pool is discovery (not free-filter).
  if (pool === 'wikiflix') {
    opts.careAccessMode = CARE_ACCESS_FREE;
  } else if (pool === 'tmdb') {
    opts.careAccessMode = CARE_ACCESS_PAID_OK;
  }
  return rankTherapeuticItems(items, mood, opts);
}

/**
 * Explicit post-mood set: 1 Wikiflix gratis + 1 TMDB discovery (distinct).
 * @param {object} mood
 * @param {{
 *   seed?: number,
 *   musicLanguageMode?: string,
 *   musicGeoZone?: string,
 *   uiLocale?: 'it'|'en',
 *   wikiflixCount?: number,
 *   tmdbCount?: number,
 *   excludeIds?: string[],
 * }} [options]
 * @returns {{ wikiflix: object[], tmdb: object[] }}
 */
export function recommendFilmSet(mood, options = {}) {
  const seed = options.seed ?? 0;
  const wikiflixCount = options.wikiflixCount ?? WIKIFLIX_FILM_COUNT;
  const tmdbCount = options.tmdbCount ?? TMDB_FILM_COUNT;
  const baseExclude = Array.isArray(options.excludeIds) ? options.excludeIds : [];
  const wikiflix = recommendFilms(mood, {
    ...options,
    count: wikiflixCount,
    seed,
    filmPool: 'wikiflix',
    careAccessMode: CARE_ACCESS_FREE,
    excludeIds: baseExclude,
  });
  const tmdb = recommendFilms(mood, {
    ...options,
    count: tmdbCount,
    seed: seed + 17,
    filmPool: 'tmdb',
    careAccessMode: CARE_ACCESS_PAID_OK,
    excludeIds: [...baseExclude, ...wikiflix.map((f) => f.id).filter(Boolean)],
  });
  return { wikiflix, tmdb };
}
